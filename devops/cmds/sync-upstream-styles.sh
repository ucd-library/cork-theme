#!/bin/bash

# Syncs campus SiteFarm source/sass into the upstream-styles branch, and records the sync
# in the upstream styles log (docs/upstream-styles-log.md) in the same commit.
# Works in a temporary worktree, so the current checkout is never touched.
# Does not merge into main; use merge-upstream-styles.sh for that.
# Usage: ./devops/cmds/sync-upstream-styles.sh [branch-or-tag]

set -e

source "$(dirname "$0")/lib/upstream-styles.sh"
require_git_version

UPSTREAM_REF="${1:-$UPSTREAM_DEFAULT_REF}"
TMP_DIR="$(mktemp -d)"
UPSTREAM_DIR="$TMP_DIR/upstream"
VENDOR_DIR="$TMP_DIR/vendor"

cleanup() {
  git -C "$ROOT_DIR" worktree remove --force "$VENDOR_DIR" 2>/dev/null || true
  rm -rf "$TMP_DIR"
}
trap cleanup EXIT

# Prints the campus commit messages that touched source/sass since the previous sync.
campus_commits() {
  if [[ -z "$PREV_SHA" ]]; then
    echo "Not available: no previous sync recorded."
  elif ! git -C "$UPSTREAM_DIR" merge-base --is-ancestor "$PREV_SHA" "$UPSTREAM_SHA" 2>/dev/null; then
    echo "Not available: the previous upstream commit is not an ancestor of this one (the campus branch changed, or campus rewrote history)."
  else
    local commits
    commits="$(git -C "$UPSTREAM_DIR" log --no-merges --date=short --format='- %ad %s' \
      "$PREV_SHA..$UPSTREAM_SHA" -- "$UPSTREAM_SASS_DIR")"
    echo "${commits:-None found.}"
  fi
}

# Prepends an entry for this sync to the log file in the vendor worktree.
write_log_entry() {
  local log="$VENDOR_DIR/$LOG_FILE"
  local modified added renamed deleted previous entries

  read -r modified added renamed deleted < <(
    git -C "$VENDOR_DIR" diff --cached -M --name-status -- "$TARGET_DIR" \
      | awk '{ n[substr($1, 1, 1)]++ } END { printf "%d %d %d %d\n", n["M"], n["A"], n["R"], n["D"] }'
  )
  previous="${PREV_SHA:0:7}"

  # keep existing entries, dropping the header so it can be rewritten
  entries=""
  if [[ -f "$log" ]]; then
    entries="$(awk 'found || /^## / { found = 1; print }' "$log")"
  fi

  mkdir -p "$(dirname "$log")"
  cat > "$log" <<EOF
# Upstream Styles Sync Log

> This file is autogenerated by \`devops/cmds/sync-upstream-styles.sh\`. Do not edit it by hand.

Each entry records one sync of campus's \`$UPSTREAM_SASS_DIR\` into \`$TARGET_DIR\` on the \`$VENDOR_BRANCH\` branch. Newest first.

## $(date +%Y-%m-%d): campus $UPSTREAM_REF ($UPSTREAM_SHORT_SHA)

- Upstream commit: \`$UPSTREAM_SHA\`
- Previous upstream commit: \`${previous:-none}\`
- Files: $modified modified, $added added, $renamed renamed, $deleted deleted

### Campus commits

$(campus_commits)
EOF

  if [[ -n "$entries" ]]; then
    printf '\n%s\n' "$entries" >> "$log"
  fi
}

# blobless, sparse clone: full commit history (for the log), but only source/sass contents
echo "Fetching $UPSTREAM_REPO at $UPSTREAM_REF"
git clone --quiet --filter=blob:none --sparse --single-branch --branch "$UPSTREAM_REF" \
  "$UPSTREAM_REPO" "$UPSTREAM_DIR"
git -C "$UPSTREAM_DIR" sparse-checkout set "$UPSTREAM_SASS_DIR"
UPSTREAM_SHA="$(git -C "$UPSTREAM_DIR" rev-parse HEAD)"
UPSTREAM_SHORT_SHA="$(git -C "$UPSTREAM_DIR" rev-parse --short HEAD)"
PREV_SHA="$(previous_upstream_sha)"

# check out the vendor branch in a temporary worktree
git -C "$ROOT_DIR" worktree add --quiet "$VENDOR_DIR" "$VENDOR_BRANCH"
mkdir -p "$VENDOR_DIR/$TARGET_DIR"
rsync -a --delete "$UPSTREAM_DIR/$UPSTREAM_SASS_DIR/" "$VENDOR_DIR/$TARGET_DIR/"
git -C "$VENDOR_DIR" add -A "$TARGET_DIR"

if git -C "$VENDOR_DIR" diff --cached --quiet; then
  echo "No upstream changes."
  exit 0
fi

write_log_entry
git -C "$VENDOR_DIR" add "$LOG_FILE"
git -C "$VENDOR_DIR" commit --quiet -F - <<EOF
campus $UPSTREAM_REF ($UPSTREAM_SHORT_SHA)

Upstream-Commit: $UPSTREAM_SHA
Upstream-Ref: $UPSTREAM_REF
EOF

echo "Committed campus $UPSTREAM_REF ($UPSTREAM_SHORT_SHA) to $VENDOR_BRANCH."
